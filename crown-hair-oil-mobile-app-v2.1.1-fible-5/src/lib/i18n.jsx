const DICTS = { ar: AR, en: EN };

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(loadLang);

  // Keep money()/formatDate() in store.js aligned before first paint.
  if (typeof setLocale === 'function') setLocale(lang);

  useEffect(() => {
    const el = document.documentElement;
    el.lang = lang;
    el.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);

  const setLang = useCallback((next) => {
    const val = next === 'en' ? 'en' : 'ar';
    setLocale(val);        // sync currency/date locale synchronously
    persistLang(val);
    setLangState(val);
  }, []);

  const t = useCallback(
    (key, vars) => interpolate((DICTS[lang] && DICTS[lang][key]) || (AR[key] ?? key), vars),
    [lang]
  );

  const value = { lang, setLang, t, dir: lang === 'ar' ? 'rtl' : 'ltr' };
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useLang must be used within <LangProvider>');
  return ctx;
}
