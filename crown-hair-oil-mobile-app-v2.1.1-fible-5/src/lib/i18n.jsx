/* ============================================================
   CROWN HAIR OIL — Mobile app internationalization (AR / EN)
   Language is persisted in localStorage under `crown_lang`, the
   same origin-shared key the landing hub and v1.2 use, so the
   choice follows the visitor across all three surfaces.
   Arabic is RTL, English is LTR; the provider keeps
   <html lang> and <html dir> in sync and mirrors the choice into
   store.js so money()/formatDate() format for the active locale.
   ============================================================ */
import { createContext, useCallback, useContext, useEffect, useState } from 'react';
import { setLocale } from './store.js';

const STORE_KEY = 'crown_lang';
export const DEFAULT_LANG = 'ar';

export function loadLang() {
  try {
    const v = localStorage.getItem(STORE_KEY);
    return v === 'en' || v === 'ar' ? v : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}
export function persistLang(lang) {
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* private mode */ }
}

